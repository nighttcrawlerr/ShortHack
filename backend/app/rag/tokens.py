"""Нормализация текста и грубая лемматизация русских окончаний.

Полноценный морфологический анализатор потребовал бы внешней библиотеки.
Для поиска по базе из десятков статей достаточно отсечь частые окончания:
«подключение», «подключения», «подключением» сводятся к одной основе.
"""
import re

STOP_WORDS = {
    "это", "для", "или", "что", "как", "при", "все", "нет", "был", "быть",
    "она", "они", "его", "ещё", "еще", "так", "уже", "там", "том", "тем",
    "мне", "меня", "вас", "вам", "наш", "под", "над", "без", "если", "чтобы",
    "здравствуйте", "добрый", "день", "спасибо", "пожалуйста", "уважением",
    "the", "and", "for", "not", "with", "you", "your",
}

_RAW_SUFFIXES = (
    "ованием", "ированием", "ениями", "ениям", "ениях", "ением",
    "ования", "ование", "ениями", "ения", "ение", "ению", "ении",
    "ами", "ями", "ого", "его", "ому", "ему", "ыми", "ими", "ках", "кам",
    "ать", "ять", "ить", "еть", "уть", "ется", "ются", "ился", "илась",
    "ов", "ев", "ий", "ый", "ая", "яя", "ое", "ее", "ые", "ие", "ка",
    "ем", "ом", "ах", "ях", "ью", "ья", "ей", "ой", "ии", "ия", "ию", "ет", "ут", "ют",
    "а", "я", "о", "е", "ы", "и", "у", "ю", "ь",
)

# От длинных окончаний к коротким, иначе «подключение» обрежется по «е»
# и не сойдётся с «подключения».
SUFFIXES = tuple(sorted(set(_RAW_SUFFIXES), key=len, reverse=True))

# Разговорные и транслитерированные написания, которые пользователи пишут
# в обращениях, приводим к тому виду, в котором они лежат в базе знаний.
SYNONYMS = {
    "впн": "vpn", "вайфай": "wifi", "вай-фай": "wifi", "wi": "wifi", "fi": "wifi",
    "аутлук": "outlook", "аутглук": "outlook", "оутлук": "outlook",
    "учетк": "учётн", "учётк": "учётн", "учетн": "учётн",
    "ноут": "ноутбук", "комп": "компьютер", "винда": "windows", "винд": "windows",
    "гигачат": "gigachat", "тачка": "компьютер", "мак": "macos",
    "логин": "логин", "пасс": "пароль", "пароль": "пароль",
}

WORD = re.compile(r"[a-zA-Zа-яёА-ЯЁ0-9_.-]{2,}", re.UNICODE)


def stem(word: str) -> str:
    if len(word) <= 4 or not re.search(r"[а-яё]", word):
        return word
    for suffix in SUFFIXES:
        if word.endswith(suffix) and len(word) - len(suffix) >= 4:
            return word[: -len(suffix)]
    return word


def tokenize(text: str) -> list[str]:
    if not text:
        return []
    words = WORD.findall(text.lower())
    out = []
    for word in words:
        if len(word) < 3 or word in STOP_WORDS:
            continue
        word = SYNONYMS.get(word, word)
        root = stem(word)
        out.append(SYNONYMS.get(root, root))
    return out
